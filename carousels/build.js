// Prepares the carousel folders for the site. Run from the site folder after adding or
// changing any item, image or JSON:  node carousels/build.js
//  1. Makes the smaller image copies (see make-image-sizes.js)
//  2. Makes HLS streams for new or changed videos (see make-video-streams.js)
//  3. Bundles every item's JSON into carousels/items.js, so the page gets them all in one
//     download instead of one per item. An item missing from the bundle still works (the
//     page fetches its JSON file), but edits to an existing item only show after a rebuild.
const fs = require("fs");
const path = require("path");

require("./make-image-sizes.js");
require("./make-video-streams.js");

const root = __dirname;
const items = {};
for (const folder of fs.readdirSync(root, { withFileTypes: true })) {
  if (!folder.isDirectory()) continue;
  for (const file of fs.readdirSync(path.join(root, folder.name))) {
    if (!file.endsWith(".json")) continue;
    const text = fs.readFileSync(path.join(root, folder.name, file), "utf8");
    try {
      (items[folder.name] ??= {})[file.slice(0, -5)] = JSON.parse(text);
    } catch (e) {
      console.error(`Skipping ${folder.name}/${file}: not valid JSON (${e.message})`);
    }
  }
}

const out =
  "// Generated by carousels/build.js from the JSON files in each carousel folder. Don't edit:\n" +
  "// edit the JSON files and run  node carousels/build.js\n" +
  `const CAROUSEL_ITEMS = ${JSON.stringify(items, null, 2)};\n`;
fs.writeFileSync(path.join(root, "items.js"), out);
const count = Object.values(items).reduce((n, f) => n + Object.keys(f).length, 0);
console.log(`carousels/items.js: ${count} items`);
